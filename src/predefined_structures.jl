"""
    create_simple_ram_sys_struct(set::Settings; unit_stiffness, unit_damping, prn)

Create a simplified `SystemStructure` for a ram-air kite with direct tether connections.

Simplified bridle without pulley system. Each tether is a single segment.

# Arguments
- `set::Settings`: Configuration parameters.

# Keywords
- `unit_stiffness`: Per-tether unit stiffness values. Default `fill(NaN, 4)`.
- `unit_damping`: Per-tether unit damping values. Default `fill(NaN, 4)`.
- `prn=true`: If true, print info messages about auto-generated components.
"""
function create_simple_ram_sys_struct(set::Settings;
                                      unit_stiffness=fill(NaN, 4),
                                      unit_damping=fill(NaN, 4),
                                      prn=true)
    set.segments = 1
    vsm_set_path = joinpath(get_data_path(), "vsm_settings.yaml")
    vsm_set = VortexStepMethod.VSMSettings(vsm_set_path; data_prefix=false)
    vsm_wing = create_vsm_wing(set, vsm_set; prn=false)
    span_fracs = [-1/2, 1/2]

    bridle_top_left = set.top_bridle_points
    bridle_top_right = [point .* [1, -1, 1] for point in bridle_top_left]

    points = [
        Point(1, bridle_top_left[2], BODY_STATIC; wing=1)
        Point(2, bridle_top_right[2], BODY_STATIC; wing=1)
        Point(3, wing_surface_pos(vsm_wing, span_fracs[1], set.bridle_fracs[4]), BODY_STATIC; wing=1)
        Point(4, wing_surface_pos(vsm_wing, span_fracs[2], set.bridle_fracs[4]), BODY_STATIC; wing=1)
        Point(5, [0, 0, -float(set.l_tether)], STATIC; transform=1)
        Point(6, [0, 0, -float(set.l_tether)], STATIC; transform=1)
        Point(7, [0, 0, -float(set.l_tether)], STATIC; transform=1)
        Point(8, [0, 0, -float(set.l_tether)], STATIC; transform=1)
        Point(9, wing_surface_pos(vsm_wing, span_fracs[1], set.bridle_fracs[1]), BODY_STATIC; wing=1)
        Point(10, wing_surface_pos(vsm_wing, span_fracs[2], set.bridle_fracs[1]), BODY_STATIC; wing=1)
    ]
    stations = [
        Station(1, [9, 3], DYNAMIC, 0.25)
        Station(2, [10, 4], DYNAMIC, 0.25)
    ]
    segments = [
        Segment(1, set, 1, 5; unit_stiffness=unit_stiffness[1], unit_damping=unit_damping[1], diameter_mm=set.power_tether_diameter)
        Segment(2, set, 2, 6; unit_stiffness=unit_stiffness[2], unit_damping=unit_damping[2], diameter_mm=set.power_tether_diameter)
        Segment(3, set, 3, 7; unit_stiffness=unit_stiffness[3], unit_damping=unit_damping[3], diameter_mm=set.steering_tether_diameter)
        Segment(4, set, 4, 8; unit_stiffness=unit_stiffness[4], unit_damping=unit_damping[4], diameter_mm=set.steering_tether_diameter)
    ]
    tethers = [
        Tether(1, [1], set.l_tether)
        Tether(2, [2], set.l_tether)
        Tether(3, [3], set.l_tether)
        Tether(4, [4], set.l_tether)
    ]
    winches = [
        Winch(1, set, [1, 2]; winch_point=5)
        Winch(2, set, [3]; winch_point=7)
        Winch(3, set, [4]; winch_point=8)
    ]
    vsm_aero = BodyAerodynamics([vsm_wing])
    vsm_solver = Solver(vsm_aero; solver_type=NONLIN, atol=2e-8, rtol=2e-8)
    wings = [VSMWing(1, vsm_aero, vsm_wing, vsm_solver, [1, 2], I(3), zeros(3))]
    transforms = [
        Transform(1, deg2rad(float(set.elevation)), deg2rad(float(set.azimuth)), deg2rad(float(set.heading));
                  base_pos=zeros(3), base_point=5, wing=1)
    ]

    return SystemStructure("simple_ram", set;
        points, stations, segments, tethers, winches, wings, transforms, prn)
end

"""
    create_tether_sys_struct(set::Settings; unit_stiffness, unit_damping, prn)

Create a simplified `SystemStructure` for testing tether dynamics only.

4 independent tethers, each a dynamic point connected to a fixed anchor.
No wing or bridle system.

# Arguments
- `set::Settings`: Configuration parameters.

# Keywords
- `unit_stiffness`: Per-tether unit stiffness values. Default `fill(NaN, 4)`.
- `unit_damping`: Per-tether unit damping values. Default `fill(NaN, 4)`.
- `prn=true`: If true, print info messages about auto-generated components.
"""
function create_tether_sys_struct(set::Settings;
                                  unit_stiffness=fill(NaN, 4),
                                  unit_damping=fill(NaN, 4),
                                  prn=true)
    points = [
        Point(:power_left, zeros(3), DYNAMIC; fix_sphere=true, transform=1)
        Point(:power_right, zeros(3), DYNAMIC; fix_sphere=true, transform=1)
        Point(:steering_left, zeros(3), DYNAMIC; fix_sphere=true, transform=1)
        Point(:steering_right, zeros(3), DYNAMIC; fix_sphere=true, transform=1)
    ]
    tethers = Tether[]

    points, tethers, power_left_anchor =
        add_tether!(points, tethers, :power_left, set, points[1];
                    unit_stiffness=unit_stiffness[1], unit_damping=unit_damping[1],
                    diameter_mm=set.power_tether_diameter)
    points, tethers, _ =
        add_tether!(points, tethers, :power_right, set, points[2];
                    unit_stiffness=unit_stiffness[2], unit_damping=unit_damping[2],
                    diameter_mm=set.power_tether_diameter)
    points, tethers, steering_left_anchor =
        add_tether!(points, tethers, :steering_left, set, points[3];
                    unit_stiffness=unit_stiffness[3], unit_damping=unit_damping[3],
                    diameter_mm=set.steering_tether_diameter)
    points, tethers, steering_right_anchor =
        add_tether!(points, tethers, :steering_right, set, points[4];
                    unit_stiffness=unit_stiffness[4], unit_damping=unit_damping[4],
                    diameter_mm=set.steering_tether_diameter)

    winches = [
        Winch(:power_winch, set, [:power_left, :power_right]; brake=true, winch_point=power_left_anchor)
        Winch(:steering_left_winch, set, [:steering_left]; brake=true, winch_point=steering_left_anchor)
        Winch(:steering_right_winch, set, [:steering_right]; brake=true, winch_point=steering_right_anchor)
    ]
    transforms = [Transform(1, deg2rad(float(set.elevation)), deg2rad(float(set.azimuth)), deg2rad(float(set.heading));
                             base_pos=zeros(3), base_point=steering_right_anchor, rot_point=:power_left)]

    return SystemStructure("tether", set; points, tethers, winches, transforms, prn)
end

"""
    create_sys_struct(set::Settings; kwargs...)

Dispatcher that calls the appropriate factory function based on `set.physical_model`.

# Arguments
- `set::Settings`: Configuration parameters from `KiteUtils.jl`.

# Keywords
- `prn=true`: If true, print info messages about auto-generated components.
- Additional keyword arguments are forwarded to the underlying factory function.
"""
function create_sys_struct(set::Settings; kwargs...)
    model = set.physical_model
    if model == "ram"
        return create_ram_sys_struct(set; kwargs...)
    elseif model == "simple_ram"
        return create_simple_ram_sys_struct(set; kwargs...)
    elseif model == "4_attach_ram"
        return create_4_attach_ram_sys_struct(set; kwargs...)
    elseif model == "tether"
        return create_tether_sys_struct(set; kwargs...)
    else
        error("Unknown physical_model: \"$model\". Supported: \"ram\", \"simple_ram\", \"4_attach_ram\", \"tether\"")
    end
end
